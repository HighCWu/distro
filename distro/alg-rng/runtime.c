#define _GNU_SOURCE
#include <errno.h>
#include <fcntl.h>
#include <grp.h>
#include <linux/if_alg.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/random.h>
#include <sys/socket.h>
#include <unistd.h>

static void fail(const char *what)
{
	printf("::vm-test::fail: AF_ALG RNG: %s errno=%d\n", what, errno);
	fflush(stdout);
	exit(1);
}
#define CHECK(ok, what) do { if (!(ok)) fail(what); } while (0)

static void close_fd(int fd)
{
	CHECK(!close(fd), "close descriptor");
	errno = 0;
	CHECK(fcntl(fd, F_GETFD) == -1 && errno == EBADF, "descriptor released");
}

static int parent(void)
{
	struct sockaddr_alg address = {.salg_family = AF_ALG};
	strcpy((char *)address.salg_type, "rng");
	strcpy((char *)address.salg_name, "stdrng");
	int fd = socket(AF_ALG, SOCK_SEQPACKET | SOCK_CLOEXEC, 0);
	CHECK(fd >= 0 && (fcntl(fd, F_GETFD) & FD_CLOEXEC), "RNG parent socket");
	CHECK(!bind(fd, (struct sockaddr *)&address, sizeof(address)), "standard RNG bind");
	return fd;
}

static int operation(int fd)
{
	int op = accept4(fd, NULL, NULL, SOCK_CLOEXEC);
	CHECK(op >= 0 && (fcntl(op, F_GETFD) & FD_CLOEXEC), "accept generator operation");
	return op;
}

static void sample(int op, unsigned char *output)
{
	unsigned char guarded[131];
	memset(guarded, 0xa5, sizeof(guarded));
	struct iovec vectors[] = {{guarded + 1, 17}, {guarded + 18, 112}};
	struct msghdr message = {.msg_iov = vectors, .msg_iovlen = 2};
	/* The upstream RNG interface caps each receive at 128 bytes. */
	CHECK(recvmsg(op, &message, 0) == 128, "standard bounded vector receive");
	CHECK(guarded[0] == 0xa5 && guarded[129] == 0xa5 && guarded[130] == 0xa5, "receive tail and guards");
	memcpy(output, guarded + 1, 128);
	unsigned char nonzero = 0;
	for (size_t i = 0; i < 128; i++) nonzero |= output[i];
	CHECK(nonzero, "generated bytes delivered");
}

int main(void)
{
	/* Wait for normal kernel CSPRNG readiness; never supply test entropy. */
	unsigned char ready;
	CHECK(getrandom(&ready, sizeof(ready), 0) == sizeof(ready), "normal kernel RNG readiness");
	int fd = parent(), op = operation(fd);
	unsigned char first[128], second[128], byte = 0xa5;
	errno = 0;
	CHECK(recv(op, &byte, 1, 0) == -1 && errno == EINVAL && byte == 0xa5, "unseeded DRBG refusal");
	errno = 0;
	CHECK(setsockopt(fd, SOL_ALG, ALG_SET_KEY, NULL, 0) == -1 && errno == EBUSY, "active operation protects parent state");
	close_fd(op);
	/* An empty personalization string requests seeding from the kernel. */
	CHECK(!setsockopt(fd, SOL_ALG, ALG_SET_KEY, NULL, 0), "standard automatic seeding");
	op = operation(fd);
	sample(op, first);
	sample(op, second);
	CHECK(memcmp(first, second, sizeof(first)), "generator progresses between requests");
	CHECK(recv(op, &byte, 0, 0) == 0 && byte == 0xa5, "zero-size receive");
	puts("AF_ALG RNG: normal kernel seeding, unseeded refusal and bounded vector output pass");

	volatile uintptr_t invalid = UINTPTR_MAX - 4095;
	errno = 0;
	CHECK(recv(op, (void *)invalid, 16, 0) == -1 && errno == EFAULT, "invalid linear-memory destination");
	sample(op, second);
	errno = 0;
	CHECK(send(op, "x", 1, 0) == -1 && errno == EOPNOTSUPP, "normal RNG is receive-only");
	sample(op, first);
	close_fd(op);
	close_fd(fd);
	puts("AF_ALG RNG: destination faults, unsupported writes and subsequent generation pass");

	CHECK(!setgroups(0, NULL) && !setgid(65534) && !setuid(65534), "ordinary user credentials");
	CHECK(getuid() == 65534 && geteuid() == 65534, "credentials applied");
	fd = parent();
	CHECK(!setsockopt(fd, SOL_ALG, ALG_SET_KEY, NULL, 0), "unprivileged automatic seeding");
	op = operation(fd);
	int sibling = operation(fd);
	close_fd(fd);
	sample(op, first);
	sample(sibling, second);
	CHECK(memcmp(first, second, sizeof(first)), "accepted operations advance the retained generator");
	close_fd(op);
	sample(sibling, first);
	close_fd(sibling);
	puts("AF_ALG RNG: unprivileged generation, parent lifetime and descriptor cleanup pass");
	return 0;
}
