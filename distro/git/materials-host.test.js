import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
  chmodSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";

const installer = fileURLToPath(new URL("./build-materials.sh", import.meta.url));
const generated = [
  "Makefile",
  "config.mak.uname",
  "GIT-BUILD-OPTIONS",
  "GIT-CFLAGS",
  "GIT-PREFIX",
  "GIT-VERSION-FILE",
  "COPYING",
  "linux-wasm-make-arguments.nul",
];
function fixture(body) {
  const root = mkdtempSync(join(tmpdir(), "git-materials-"));
  try {
    const tree = join(root, "build ' tree");
    const output = join(root, "materials");
    const runtime = join(root, "runtime");
    const files = new Map();
    function input(path, bytes) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, bytes);
      files.set(path, Buffer.from(bytes));
      return path;
    }
    for (const name of generated) input(join(tree, name), `${name}\0literal $HOME ' →\n`);
    writeFileSync(join(tree, "GIT-LDFLAGS"), "-Wl,literal\n");
    input(join(tree, "GIT-BUILD-OPTIONS"), `touch '${root}/must-not-execute'\n`);
    for (const name of ["usr/bin/git", "usr/libexec/git-core/git-remote-http"])
      input(join(runtime, name), new Uint8Array([0, 97, 115, 109, 0, 255]));
    const recipe = input(join(root, "package.nix"), "# exact recipe\n");
    const metadata = input(join(root, "metadata.json"), '{"schemaVersion":1}\n');
    const readme = input(
      join(root, "README.md"),
      readFileSync(new URL("./build-materials.README.md", import.meta.url)),
    );
    const patches = [
      input(join(root, "first/same.patch"), "first override\n"),
      input(join(root, "second/same.patch"), "second override\n"),
    ];
    const compiler = join(root, "compiler");
    writeFileSync(
      compiler,
      '#!/bin/sh\ntest "$#" = 1 && test "$1" = --version || exit 2\nprintf "%s\\n" "fixture compiler"\n',
    );
    chmodSync(compiler, 0o755);
    const run = () =>
      spawnSync(
        "bash",
        [installer, tree, output, runtime, recipe, metadata, compiler, readme, ...patches],
        {
          encoding: "utf8",
          timeout: 10000,
          env: {
            ...process.env,
            NIX_CFLAGS_COMPILE: "-I/path with spaces",
            NIX_CFLAGS_LINK: "-Wl,--shared-memory",
            NIX_LDFLAGS: "-L/static",
            GIT_MATERIAL_TEST_SECRET: "never collect this",
          },
        },
      );
    const check = (cwd, manifest) =>
      spawnSync("sha256sum", ["--check", manifest], { cwd, encoding: "utf8", timeout: 5000 });
    body({ root, tree, output, runtime, files, patches, compiler, run, check });
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test("Git material collector preserves generated bytes, ordered override patches and final binary digests", () => {
  fixture(({ root, tree, output, runtime, patches, run, check }) => {
    const result = run();
    assert.equal(result.status, 0, result.stderr);
    for (const name of generated)
      assert.deepEqual(readFileSync(join(output, name)), readFileSync(join(tree, name)));
    assert.deepEqual(
      readFileSync(join(output, "GIT-LDFLAGS")),
      readFileSync(join(tree, "GIT-LDFLAGS")),
    );
    assert.equal(readFileSync(join(output, "GIT-LDFLAGS.status"), "utf8"), "present\n");
    for (const [index, patch] of patches.entries())
      assert.deepEqual(
        readFileSync(join(output, "patches", `${String(index).padStart(3, "0")}.patch`)),
        readFileSync(patch),
      );
    assert.equal(readFileSync(join(output, "compiler-version.txt"), "utf8"), "fixture compiler\n");
    assert.equal(
      readFileSync(join(output, "toolchain-environment.nul"), "utf8"),
      "NIX_CFLAGS_COMPILE=-I/path with spaces\0NIX_CFLAGS_LINK=-Wl,--shared-memory\0NIX_LDFLAGS=-L/static\0",
    );
    assert.equal(existsSync(join(root, "must-not-execute")), false);
    assert.equal(existsSync(join(runtime, "build.json")), false);
    assert.equal(check(output, "SHA256SUMS").status, 0);
    assert.equal(check(runtime, join(output, "BINARY_SHA256SUMS")).status, 0);
    writeFileSync(join(runtime, "usr/libexec/git-core/git-remote-http"), "changed final binary");
    assert.notEqual(check(runtime, join(output, "BINARY_SHA256SUMS")).status, 0);
  });
});

test("Git collector records legitimately absent link tracking and rejects an empty present file", () => {
  fixture(({ tree, output, run, check }) => {
    writeFileSync(join(tree, "GIT-LDFLAGS"), "");
    assert.notEqual(run().status, 0);
    rmSync(join(tree, "GIT-LDFLAGS"));
    assert.equal(run().status, 0);
    assert.equal(readFileSync(join(output, "GIT-LDFLAGS.status"), "utf8"), "absent\n");
    assert.equal(existsSync(join(output, "GIT-LDFLAGS")), false);
    assert.equal(check(output, "SHA256SUMS").status, 0);
  });
});

test("Git collector rejects each missing or empty required input", () => {
  fixture(({ files, run }) => {
    for (const [path, bytes] of files) {
      for (const failure of ["missing", "empty"]) {
        if (failure === "missing") rmSync(path);
        else writeFileSync(path, "");
        assert.notEqual(run().status, 0, `${failure}: ${path}`);
        writeFileSync(path, bytes);
      }
    }
  });
});

test("Git collector rejects failed or empty compiler identification and detects changed material records", () => {
  fixture(({ compiler, output, run, check }) => {
    for (const script of ["#!/bin/sh\nexit 7\n", "#!/bin/sh\nexit 0\n"]) {
      writeFileSync(compiler, script);
      assert.notEqual(run().status, 0);
    }
    writeFileSync(compiler, "#!/bin/sh\necho fixture\n");
    assert.equal(run().status, 0);
    for (const name of ["GIT-CFLAGS", "build.json", "patches/001.patch", "BINARY_SHA256SUMS"]) {
      const path = join(output, name),
        original = readFileSync(path);
      writeFileSync(path, "corrupt record");
      assert.notEqual(check(output, "SHA256SUMS").status, 0, name);
      writeFileSync(path, original);
    }
  });
});

test("both Git widths retain separate materials without moving runtime paths and CI uploads only verified records", () => {
  const recipe = readFileSync(new URL("./package.nix", import.meta.url), "utf8");
  for (const required of [
    '"buildMaterials"',
    "setOutputFlags = false;",
    "moveToDev = false;",
    'meta.outputsToInstall = [ "out" ];',
    "postFixup = ''",
    '"$CC" ${./build-materials.README.md} ${pkgs.lib.escapeShellArgs (map toString finalAttrs.patches)}',
    "inherit (finalAttrs) makeFlags;",
    "finalAttrs.finalPackage.buildMaterials",
    "MATERIALS_SHA256SUMS",
    'cmp "$materials/patches/$name" "$patch"',
  ])
    assert.ok(recipe.includes(required), required);
  const workflow = readFileSync(new URL("../../.github/workflows/ci.yml", import.meta.url), "utf8");
  for (const required of [
    "git-check-build-materials) package=git",
    "git-wasm64-check-build-materials) package=git-wasm64",
    "git-build-materials/verification/MATERIALS_SHA256SUMS",
    "sha256sum --check verification/MATERIALS_SHA256SUMS",
    "name: git-build-materials-${{ matrix.check }}-${{ github.sha }}",
  ])
    assert.ok(workflow.includes(required), required);
});

test("actual Git artifact collection checks copied records and the verification manifests for both widths", () => {
  const workflow = readFileSync(new URL("../../.github/workflows/ci.yml", import.meta.url), "utf8");
  const block = workflow.split("      - name: Collect verified Git build materials\n")[1];
  const body = block
    .split("        run: |\n")[1]
    .split("\n      - uses:")[0]
    .replace(/^          /gm, "");
  for (const mode of ["git", "git-wasm64", "record", "verification", "missing", "wrong-check"]) {
    fixture(({ root, output, run }) => {
      assert.equal(run().status, 0);
      const verification = join(root, "verification");
      mkdirSync(verification);
      for (const [from, to] of [
        ["SHA256SUMS", "MATERIALS_SHA256SUMS"],
        ["BINARY_SHA256SUMS", "BINARY_SHA256SUMS"],
      ])
        copyFileSync(join(output, from), join(verification, to));
      const hashes = spawnSync("sha256sum", ["MATERIALS_SHA256SUMS", "BINARY_SHA256SUMS"], {
        cwd: verification,
      });
      assert.equal(hashes.status, 0);
      writeFileSync(join(verification, "SHA256SUMS"), hashes.stdout);
      if (mode === "record") writeFileSync(join(output, "GIT-CFLAGS"), "changed record");
      if (mode === "verification")
        writeFileSync(join(verification, "BINARY_SHA256SUMS"), "changed verification");
      if (mode === "missing") rmSync(join(output, "build.json"));
      const cwd = join(root, "artifact-work");
      mkdirSync(cwd);
      const packageName = mode === "git-wasm64" ? "git-wasm64" : "git";
      const fakeNix = `nix() {
        if [ "$1" = eval ] && [ "$2" = --raw ]; then
          case "$3" in
            ".#$EXPECTED_PACKAGE.buildMaterials.outPath") printf '%s\\n' "$FIXTURE_MATERIALS" ;;
            ".#$EXPECTED_PACKAGE.checks.build-materials.outPath") printf '%s\\n' "$FIXTURE_VERIFICATION" ;;
            *) return 2 ;;
          esac
        elif [ "$1" = path-info ]; then test -d "$2" && test -d "$3";
        else return 3; fi
      }\n`;
      const result = spawnSync("bash", ["-euo", "pipefail", "-c", fakeNix + body], {
        cwd,
        encoding: "utf8",
        timeout: 10000,
        env: {
          ...process.env,
          CHECK:
            mode === "wrong-check" ? "git-check-wrong" : `${packageName}-check-build-materials`,
          EXPECTED_PACKAGE: packageName,
          FIXTURE_MATERIALS: output,
          FIXTURE_VERIFICATION: verification,
        },
      });
      if (mode === "git" || mode === "git-wasm64") {
        assert.equal(result.status, 0, result.stderr);
        assert.deepEqual(
          readFileSync(join(cwd, "git-build-materials/GIT-CFLAGS")),
          readFileSync(join(output, "GIT-CFLAGS")),
        );
      } else assert.notEqual(result.status, 0, mode);
    });
  }
});
